#!/usr/bin/env node
// Maintainer tool: writes docs/COVERAGE.md, the objective-to-content coverage
// summary, from the generated runtime data. Run: node tools/coverage-report.js
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const LMS = path.join(__dirname, "..", "lms");
const load = (f, g) => {
  const sb = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(LMS, f), "utf8"), sb);
  return sb.window[g];
};
const data = load("data.js", "SAPC02_LMS_DATA");
const content = load("content.js", "SAPC02_LESSON_CONTENT");
const labs = load("labs.js", "SAPC02_LABS_DATA").labs;
const kc = load("knowledge-checks.js", "SAPC02_KNOWLEDGE_CHECKS");
const quiz = load("quiz-data.js", "SAPC02_QUIZ").questions;

const rows = [];
let o = `# SAP-C02 coverage summary\n\nGenerated by \`tools/coverage-report.js\` from the runtime data. Skills measured as of ${data.studyGuide.skillsMeasuredAsOf} (${data.studyGuide.url}).\n\n`;
o += `## Per chapter\n\n| Chapter | Exam weight | Lessons | Topics | Objectives | Labs | Knowledge checks | Practice questions |\n|---|---|---|---|---|---|---|---|\n`;
let t = { l: 0, t: 0, ob: 0, labs: 0, kc: 0, q: 0 };
data.modules.forEach((m) => {
  const topics = m.lessons.reduce((n, l) => n + (content[`${m.id}:${l.id}`]?.topics.length || 0), 0);
  const ob = m.lessons.reduce((n, l) => n + l.objectives.length, 0);
  const nl = labs.filter((x) => x.moduleId === m.id).length;
  const nk = m.lessons.reduce((n, l) => n + (kc[`${m.id}:${l.id}`]?.length || 0), 0);
  const nq = quiz.filter((q) => q.moduleId === m.id).length;
  o += `| ${m.title} | ${m.weight} | ${m.lessons.length} | ${topics} | ${ob} | ${nl} | ${nk} | ${nq} |\n`;
  t.l += m.lessons.length; t.t += topics; t.ob += ob; t.labs += nl; t.kc += nk; t.q += nq;
});
o += `| **Total** | | ${t.l} | ${t.t} | ${t.ob} | ${t.labs} | ${t.kc} | ${t.q} |\n\n`;
o += `## Objective to lesson map\n\nEvery skills-measured bullet listed under a technical domain appears as a lesson objective (shown as a scenario in the app). Quiz counts are questions whose topic equals the lesson title.\n\n`;
data.modules
  .filter((m) => !["orientation", "review"].includes(m.id))
  .forEach((m) => {
    o += `### ${m.title} (${m.weight})\n\n| Lesson | Objectives | Topics | Labs | Quiz Qs |\n|---|---|---|---|---|\n`;
    m.lessons.forEach((l) => {
      const nl = labs.filter((x) => x.moduleId === m.id && x.lessonId === l.id).map((x) => x.id).join(", ") || "none";
      const nq = quiz.filter((q) => q.moduleId === m.id && q.topic === l.title).length;
      o += `| ${l.title} | ${l.objectives.length} | ${content[`${m.id}:${l.id}`].topics.length} | ${nl} | ${nq} |\n`;
    });
    o += "\n";
  });
const unmatched = quiz.filter((q) => !data.modules.find((m) => m.id === q.moduleId)?.lessons.some((l) => l.title === q.topic));
o += `## Checks\n\n- Practice questions whose topic does not equal a lesson title: ${unmatched.length}${unmatched.length ? " (" + unmatched.map((q) => q.id).join(", ") + ")" : ""}.\n`;
const lessonsNoQ = data.modules.filter((m) => !["orientation", "review"].includes(m.id)).flatMap((m) => m.lessons.filter((l) => !quiz.some((q) => q.moduleId === m.id && q.topic === l.title)).map((l) => `${m.id}:${l.id}`));
o += `- Technical lessons with no practice question: ${lessonsNoQ.length ? lessonsNoQ.join(", ") : "none"}.\n`;
fs.mkdirSync(path.join(__dirname, "..", "docs"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "docs", "COVERAGE.md"), o);
console.log(o.split("## Checks")[1]);
