#!/usr/bin/env node
// Maintainer tool: assembles the runtime data files in lms/ from the authored
// sources in source/. Run: node tools/build-content.js
// Validates ids, cross-references and URLs, and fails on any problem.
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "source");
const OUT = path.join(ROOT, "lms");
const course = require(path.join(SRC, "course.cjs"));
const extra = require(path.join(SRC, "extra-lessons.cjs"));
const labsSrc = require(path.join(SRC, "labs.cjs"));
const lessonsJson = JSON.parse(fs.readFileSync(path.join(SRC, "lessons.json"), "utf8"));
const urls = JSON.parse(fs.readFileSync(path.join(SRC, "learn-urls.json"), "utf8"));
const optional = (name) => (fs.existsSync(path.join(SRC, name)) ? require(path.join(SRC, name)) : null);
const kcSrc = optional("knowledge-checks.cjs");
const quizSrc = optional("quiz.cjs");

const errors = [];
const fail = (msg) => errors.push(msg);
const AS_OF = course.AS_OF;
const VERIFIED = "2026-10-30";

// ── URL validation ───────────────────────────────────────
const urlOk = (u) => /^https:\/\/(docs\.aws\.amazon\.com|aws\.amazon\.com|skillbuilder\.aws|repost\.aws\/knowledge-center)\/[A-Za-z0-9/_\-.#?=%]*$/.test(u);
Object.entries(urls).forEach(([k, u]) => urlOk(u) || fail(`bad url ${k}: ${u}`));
const urlFor = (key) => {
  const fixed = key === "gateway-gateway-transit" ? "gateway-transit" : key;
  if (!urls[fixed]) fail(`unknown learn key: ${key}`);
  return urls[fixed];
};
const label = (key) => {
  const fixed = key === "gateway-gateway-transit" ? "gateway-transit" : key;
  if (!course.LABELS[fixed]) fail(`no label for learn key: ${key}`);
  return course.LABELS[fixed];
};
const link = (key) => ({ label: label(key), url: urlFor(key) });

const banner = (name) => `// ${name}: generated by tools/build-content.js from source/. Do not edit by hand.\n`;
const write = (file, global, value) => {
  fs.writeFileSync(path.join(OUT, file), `${banner(file)}window.${global} = ${JSON.stringify(value, null, 1)};\n`);
};

// ── Lessons / content.js ─────────────────────────────────
const allLessonSources = { ...lessonsJson };
Object.entries(extra.lessons).forEach(([k, v]) => {
  if (allLessonSources[k]) fail(`duplicate lesson content ${k}`);
  allLessonSources[k] = v;
});
const content = {};
Object.entries(allLessonSources).forEach(([key, lesson]) => {
  content[key] = { topics: lesson.topics };
});

const ids = new Set();
const uniq = (id, what) => {
  if (ids.has(id)) fail(`duplicate id (${what}): ${id}`);
  ids.add(id);
};

// ── learn-links.js ───────────────────────────────────────
const learn = {};
course.modules.forEach((m) =>
  m.lessons.forEach((l) => {
    const key = `${m.id}:${l.id}`;
    const src = allLessonSources[key];
    if (!src) return fail(`no content for lesson ${key}`);
    const map = {};
    src.topics.forEach((t) => {
      const keys = (course.learnByTopic[key] || {})[t.title];
      if (keys && keys.length) map[t.title] = keys.map(link);
    });
    if (Object.keys(map).length) learn[key] = map;
  })
);
// Every learnByTopic title must exist somewhere.
Object.entries(course.learnByTopic).forEach(([key, byTitle]) => {
  const titles = new Set(((allLessonSources[key] || {}).topics || []).map((t) => t.title));
  Object.keys(byTitle).forEach((t) => titles.has(t) || fail(`learnByTopic title not in ${key}: ${t}`));
});

// ── data.js ──────────────────────────────────────────────
const MIND = course.mindMaps;
const COURSE_MAP = {
  title: "SAP-C02 course map",
  body: "The four content domains and how the chapters in this app map to them.",
  branches: course.domains.map((d) => `${d.title} (${d.weight})`),
  asset: "assets/sapc02-course-map.svg",
  alt: "SAP-C02 course map: four content domains and their weights, mapped to the four technical chapters",
};
const modules = course.modules.map((m) => {
  uniq(m.id, "module");
  const mm = MIND[m.id];
  const lessons = m.lessons.map((l) => {
    uniq(`${m.id}:${l.id}`, "lesson");
    return {
      id: l.id,
      title: l.title,
      duration: l.duration,
      summary: l.summary,
      objectives: l.objectives,
      practice: l.practice,
      sources: (l.sources || []).map(link),
    };
  });
  return {
    id: m.id,
    title: m.title,
    shortTitle: m.shortTitle,
    accent: m.accent,
    domain: m.domain,
    weight: m.weight,
    duration: m.duration,
    overview: m.overview,
    objectives: m.objectives || [],
    takeaways: m.takeaways || [],
    flashcards: extra.flashcards[m.id] || [],
    mindMap: m.id === "orientation" ? COURSE_MAP : mm ? { ...mm, asset: `assets/sapc02-${m.id}-map.svg`, alt: `${mm.title} mind map` } : null,
    labs: labsSrc.labs.filter((x) => x.moduleId === m.id).map((x) => x.id),
    sourceDocs: [],
    lessons,
  };
});

const lessonIndex = new Set(modules.flatMap((m) => m.lessons.map((l) => `${m.id}:${l.id}`)));
Object.keys(content).forEach((k) => lessonIndex.has(k) || fail(`content for unknown lesson ${k}`));

const totalLabs = labsSrc.labs.length;
const data = {
  generatedAt: VERIFIED,
  title: "SAP-C02 Study Buddy",
  sourceSummary: `Authored from the SAP-C02 exam guide (${AS_OF}) and AWS documentation retrieved through the AWS MCP server.`,
  sourceObjectives: "SAP-C02 exam guide (docs/)",
  sourceQuiz: "Original authored questions",
  studyGuide: { url: urlFor("exam-page"), skillsMeasuredAsOf: AS_OF },
  coverImage: "assets/sapc02-course-map.svg",
  summary: {
    executive: [
      "Design optimized AWS solutions across four domains: organizational complexity, new solutions, continuous improvement, and migration and modernization.",
    ],
    takeaways: [
      "Read the requirement, the hard constraints and the optimisation keyword separately before comparing options.", "Apply the decision rules in each lesson summary: they tie each service choice to a requirement.", "Treat AWS documentation as the authority and re-verify limits, prices and service availability before relying on them.",
    ],
    examNotes: [
      "The exam guide states a minimum passing scaled score of 750 on a scale of 100-1,000, with 65 scored and 10 unscored questions.",
      "This app does not predict your exam score; question counts and durations in the practice quiz are app settings, not official figures.",
    ],
    services: [
      { name: "Amazon VPC, Direct Connect, Transit Gateway", purpose: "Network connectivity across VPCs and to on-premises." },
      { name: "AWS Organizations and Control Tower", purpose: "Multi-account structure and governance." },
      { name: "IAM, KMS, GuardDuty, Security Hub", purpose: "Identity, encryption and security services." },
      { name: "Route 53, ELB, Auto Scaling, multi-AZ and multi-Region", purpose: "Reliability and business continuity." },
      { name: "CloudFormation, Systems Manager, CloudWatch", purpose: "Deployment, operations and monitoring." },
      { name: "Migration services, Lambda, containers, purpose-built databases", purpose: "Migration and modernization." },
    ],
  },
  examDomains: course.domains,
  modules,
  documents: [],
  quiz: [],
};

// ── labs.js / lab-guides.js ──────────────────────────────
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const modById = Object.fromEntries(modules.map((m) => [m.id, m]));
const labs = [];
const guides = {};
labsSrc.labs.forEach((lab) => {
  uniq(lab.id, "lab");
  if (!modById[lab.moduleId]) fail(`lab ${lab.id}: unknown module ${lab.moduleId}`);
  if (!lessonIndex.has(`${lab.moduleId}:${lab.lessonId}`)) fail(`lab ${lab.id}: unknown lesson ${lab.lessonId}`);
  const tasks = lab.tasks.map((t) => {
    const steps = `<ol>${t.steps.map((s) => `<li>${esc(s)}</li>`).join("")}</ol>`;
    const code = t.code ? `<pre><code>${esc(t.code)}</code></pre>` : "";
    return { title: t.title, subtasks: t.steps, html: steps + code };
  });
  labs.push({
    id: lab.id,
    title: lab.title,
    repoModule: modById[lab.moduleId].shortTitle,
    origin: "authored",
    description: lab.description,
    duration: lab.duration,
    durationMinutes: lab.durationMinutes,
    level: lab.level,
    primaryTopics: lab.primaryTopics,
    scenario: lab.scenario,
    jobSkills: lab.jobSkills,
    tasks,
    tools: lab.tools,
    keyTakeaways: lab.keyTakeaways,
    cleanup: lab.cleanup,
    supportingFiles: [],
    url: "",
    path: "",
    moduleId: lab.moduleId,
    lessonId: lab.lessonId,
  });
  const g = lab.guide;
  if (!g || g.preCheck.length < 1 || g.postCheck.length < 1) fail(`lab ${lab.id}: missing guide checks`);
  [...g.preCheck, ...g.postCheck].forEach((q) => {
    if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= q.options.length) fail(`lab ${lab.id}: bad check answer`);
  });
  const { docs, ...rest } = g;
  guides[lab.id] = { ...rest, docs: (docs || []).map(link) };
});

write("data.js", "SAPC02_LMS_DATA", data);
write("content.js", "SAPC02_LESSON_CONTENT", content);
write("learn-links.js", "SAPC02_TOPIC_LEARN", learn);
write("labs.js", "SAPC02_LABS_DATA", {
  generator: "tools/build-content.js",
  generatedAt: VERIFIED,
  origin: "authored",
  repoUrl: "",
  sync: null,
  labs,
  demos: [],
  _warnings: [],
});
write("lab-guides.js", "SAPC02_LAB_GUIDES", guides);

// ── knowledge checks and quiz ────────────────────────────
let kcCount = 0;
if (kcSrc) {
  const kc = kcSrc.checks;
  Object.entries(kc).forEach(([key, list]) => {
    if (!lessonIndex.has(key)) fail(`knowledge check for unknown lesson ${key}`);
    list.forEach((q) => {
      uniq(q.id, "kc");
      kcCount++;
      const keys = q.options.map((o) => o.key);
      if (!q.answer.split("").every((a) => keys.includes(a))) fail(`kc ${q.id}: answer not in options`);
      if (!q.explanation) fail(`kc ${q.id}: no explanation`);
      if (q.refKey) q.reference = link(q.refKey);
      delete q.refKey;
      if (!q.reference || !urlOk(q.reference.url)) fail(`kc ${q.id}: missing reference`);
    });
  });
  write("knowledge-checks.js", "SAPC02_KNOWLEDGE_CHECKS", kc);
}

let quizCount = 0;
if (quizSrc) {
  const seen = new Set();
  const counts = { mcq: 0, yesno: 0, dragdrop: 0, multi: 0, hotspot: 0 };
  const questions = quizSrc.questions.map((q, i) => {
    uniq(q.id, "quiz");
    if (!modById[q.moduleId] || ["orientation", "review"].includes(q.moduleId)) fail(`quiz ${q.id}: bad moduleId ${q.moduleId}`);
    const norm = q.question.toLowerCase().replace(/\W+/g, " ").trim();
    if (seen.has(norm)) fail(`quiz ${q.id}: duplicate question text`);
    seen.add(norm);
    if (!q.explanation) fail(`quiz ${q.id}: no explanation`);
    const reference = q.refKey ? urlFor(q.refKey) : q.reference;
    if (!reference || !urlOk(reference)) fail(`quiz ${q.id}: missing/invalid reference`);
    if (!q.interactive) {
      const keys = q.options.map((o) => o.key);
      const ans = String(q.answer).split("");
      ans.forEach((a) => keys.includes(a) || fail(`quiz ${q.id}: answer ${a} not in options`));
      if (q.qtype === "multi" && ans.length < 2) fail(`quiz ${q.id}: multi needs 2+ answers`);
      if (q.qtype !== "multi" && ans.length !== 1) fail(`quiz ${q.id}: single answer expected`);
    }
    counts[q.qtype] = (counts[q.qtype] || 0) + 1;
    const { refKey, ...rest } = q;
    return { number: i + 1, images: [], interactive: null, verified: 2, ...rest, reference };
  });
  quizCount = questions.length;
  write("quiz-data.js", "SAPC02_QUIZ", { generatedAt: VERIFIED, source: "Original authored questions, verified against AWS documentation", counts, questions });
}

if (errors.length) {
  console.error(`build-content: ${errors.length} problem(s)\n  ${errors.join("\n  ")}`);
  process.exit(1);
}
const topics = Object.values(content).reduce((n, l) => n + l.topics.length, 0);
const blocks = Object.values(content).reduce((n, l) => n + l.topics.reduce((m, t) => m + t.blocks.length, 0), 0);
console.log(
  `build-content ok: ${modules.length} modules, ${Object.keys(content).length} lessons, ${topics} topics, ${blocks} blocks, ${labs.length} labs, ${kcCount} knowledge checks, ${quizCount} quiz questions`
);
